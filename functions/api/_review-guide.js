const WORN = ['作り手として何よりの励み', '心より感謝申し上げます', '寄り添', '心地よい', '日常の中で', '何よりの喜び', '精進してまいります', '温かいお言葉', '身の引き締まる', '胸を打たれ'];

export function lintReply(text) {
  const t = typeof text === 'string' ? text : '';
  const out = [];
  for (const [re, msg] of NG_RULES) if (re.test(t)) out.push({ level: 'ng', msg });
  for (const [re, msg] of FACT_RULES) if (re.test(t)) out.push({ level: 'ng', msg });
  for (const [re, msg] of WARN_RULES) if (re.test(t)) out.push({ level: 'warn', msg });
  const worn = WORN.filter(w => t.includes(w));
  if (worn.length >= 2) out.push({ level: 'warn', msg: `使い古した言い回しが${worn.length}つ（${worn.join('・')}）` });
  if (!/香司\s*柴垣\s*$/.test(t.trim())) out.push({ level: 'warn', msg: '末尾に署名「香司　柴垣」が無い' });
  const len = t.replace(/香司\s*柴垣\s*$/, '').replace(/\s/g, '').length;
  if (len < 40) out.push({ level: 'warn', msg: `短すぎる（${len}字）` });
  if (len > 320) out.push({ level: 'warn', msg: `長すぎる（${len}字）` });
  return out;
}
